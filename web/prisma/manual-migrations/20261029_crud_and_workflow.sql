ALTER TABLE nota_tecnica ADD COLUMN IF NOT EXISTS archived_at timestamptz;
ALTER TABLE allegato ADD COLUMN IF NOT EXISTS archived_at timestamptz;

CREATE TABLE IF NOT EXISTS stato_transizione (
  id_transizione integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fk_stato_da integer NOT NULL REFERENCES stato(id_stato) ON DELETE RESTRICT,
  fk_stato_a integer NOT NULL REFERENCES stato(id_stato) ON DELETE RESTRICT,
  CONSTRAINT uq_stato_transizione UNIQUE (fk_stato_da, fk_stato_a),
  CONSTRAINT ck_stato_transizione_diversa CHECK (fk_stato_da <> fk_stato_a)
);

INSERT INTO stato_transizione (fk_stato_da, fk_stato_a)
SELECT da.id_stato, a.id_stato
FROM (VALUES
  ('Segnalato', 'Preso in carico'),
  ('Preso in carico', 'In lavorazione'),
  ('In lavorazione', 'Sospeso'),
  ('In lavorazione', 'Risolto'),
  ('Sospeso', 'In lavorazione')
) AS transizioni(da_nome, a_nome)
JOIN stato da ON da.nome = transizioni.da_nome
JOIN stato a ON a.nome = transizioni.a_nome
ON CONFLICT (fk_stato_da, fk_stato_a) DO NOTHING;
