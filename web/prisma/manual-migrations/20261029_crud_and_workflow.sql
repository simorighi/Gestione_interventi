ALTER TABLE stato ADD COLUMN IF NOT EXISTS archived_at timestamptz;
ALTER TABLE segnalazione ADD COLUMN IF NOT EXISTS archived_at timestamptz;
ALTER TABLE assegnazione ADD COLUMN IF NOT EXISTS archived_at timestamptz;
